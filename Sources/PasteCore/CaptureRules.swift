import Foundation

public struct CaptureRules: Sendable {
    public var excludedBundleIDs: Set<String>

    public static let defaultExcluded: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "com.dashlane.dashlanephonefinal",
        "com.lastpass.LastPass",
        "org.keepassxc.keepassxc",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
    ]

    public static let rejectedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public init(excludedBundleIDs: Set<String> = CaptureRules.defaultExcluded) {
        self.excludedBundleIDs = excludedBundleIDs
    }

    public func shouldCapture(sourceBundleID: String?, types: [String]) -> Bool {
        if let id = sourceBundleID, excludedBundleIDs.contains(id) { return false }
        return !types.contains { Self.rejectedTypes.contains($0) }
    }
}
